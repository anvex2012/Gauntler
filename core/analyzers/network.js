'use strict';
const { findAll, truncate, strEntropy, isDoc: isDocName } = require('../utils');
const isDoc = (ctx) => isDocName(ctx.name);

const URL_RE = /\b(?:https?|ftp|wss?|smb|file|tcp|udp):\/\/[^\s"'<>()\\^`{|}\x00-\x1f]{3,2000}/gi;
const IP_RE = /\b(?:(?:25[0-5]|2[0-4]\d|1?\d?\d)\.){3}(?:25[0-5]|2[0-4]\d|1?\d?\d)\b/g;
const IPV6_RE = /\b(?:[0-9a-f]{1,4}:){7}[0-9a-f]{1,4}\b/gi;
const ONION_RE = /\b[a-z2-7]{16}(?:[a-z2-7]{40})?\.onion\b/gi;
const DOMAIN_RE = /\b(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+(?:com|net|org|info|biz|ru|cn|tk|ml|ga|cf|gq|xyz|top|zip|mov|click|io|co|me|cc|pw|su|in|it|de|uk|fr|nl|br|online|site|live|shop|store|app|dev|cloud|link|club|icu|cyou|sbs|buzz|monster|rest|work|support|win|bid|loan|download|review|stream)\b/gi;
const WALLETS = [
  ['BTC', /\b(?:bc1[ac-hj-np-z02-9]{39,59}|[13][a-km-zA-HJ-NP-Z1-9]{25,34})\b/g, (s) => s.startsWith('bc1') || (/[a-z]/.test(s) && /[A-Z]/.test(s) && /\d/.test(s))],
  ['ETH', /\b0x[a-fA-F0-9]{40}\b/g, () => true],
  ['XMR', /\b4[0-9AB][1-9A-HJ-NP-Za-km-z]{93}\b/g, () => true],
  ['LTC', /\b(?:ltc1[a-z0-9]{39,59}|[LM][a-km-zA-HJ-NP-Z1-9]{26,33})\b/g, (s) => s.startsWith('ltc1') || (/[a-z]/.test(s) && /\d/.test(s))],
  ['TRX', /\bT[A-Za-z1-9]{33}\b/g, (s) => /[a-z]/.test(s) && /\d/.test(s)],
  ['SOL', /\b[1-9A-HJ-NP-Za-km-z]{43,44}\b/g, () => false],
];

const BAD_TLD = /\.(tk|ml|ga|cf|gq|xyz|top|zip|mov|click|country|kim|work|rest|cam|loan|monster|buzz|support|icu|cyou|sbs|bid|win|download|review|stream|pw|su)$/i;
const SHORTENERS = /^(bit\.ly|tinyurl\.com|t\.co|goo\.gl|is\.gd|cutt\.ly|rb\.gy|shorturl\.at|ow\.ly|buff\.ly|rebrand\.ly|t\.ly|tiny\.cc|s\.id|v\.gd|qrco\.de)$/i;
const ABUSED = /(pastebin\.com|paste\.ee|hastebin|ghostbin|rentry\.co|transfer\.sh|anonfiles|file\.io|temp\.sh|gofile\.io|catbox\.moe|ngrok(-free)?\.(io|app|dev)|trycloudflare\.com|cdn\.discordapp\.com\/attachments|raw\.githubusercontent\.com|gist\.githubusercontent\.com|duckdns\.org|no-ip\.|ddns\.net|hopto\.org|serveo\.net|portmap\.io|workers\.dev|pages\.dev|000webhost|glitch\.me|firebaseapp\.com|web\.app|blogspot\.|ipfs\.|dweb\.link|mediafire\.com|mega\.nz|dropbox\.com\/s\/|drive\.google\.com\/uc)/i;
const IP_LOOKUP = /(ipinfo\.io|ip-api\.com|api\.ipify\.org|icanhazip\.com|checkip\.amazonaws\.com|ifconfig\.me|wtfismyip|myexternalip)/i;
const BRANDS = ['paypal', 'apple', 'microsoft', 'office365', 'outlook', 'amazon', 'netflix', 'google', 'facebook', 'instagram', 'poste', 'postepay', 'intesa', 'unicredit', 'bancoposta', 'inps', 'agenziaentrate', 'dhl', 'fedex', 'ups', 'binance', 'coinbase', 'metamask'];
const LEGIT_BRAND_HOST = /(^|\.)(paypal|apple|microsoft|office|outlook|live|amazon|netflix|google|facebook|instagram|poste|intesasanpaolo|unicredit|inps|agenziaentrate|dhl|fedex|ups|binance|coinbase|metamask)\.(com|it|net|io|de|co\.uk|gov\.it)$/i;

const EXAMPLE = /(^|\.)(example\.(com|org|net)|localhost|test|invalid|local|host|domain|server|c|b)$/i;
const LURE_WORDS = /(login|log-in|signin|sign-in|secure|verify|verification|account|update|support|auth|wallet|bank|confirm|service|helpdesk|unlock|recover|billing|payment|refund|prize|gift|bonus|free|claim)/i;
const SLD = /^(co|com|org|net|gov|ac|edu)\.[a-z]{2}$/;
function registrable(h) {
  const p = h.split('.');
  if (p.length >= 3 && SLD.test(p.slice(-2).join('.'))) return p[p.length - 3];
  return p.length >= 2 ? p[p.length - 2] : h;
}

function privateIp(ip) {
  const [a, b] = ip.split('.').map(Number);
  return a === 10 || a === 127 || a === 0 || (a === 192 && b === 168) || (a === 172 && b >= 16 && b <= 31) || (a === 169 && b === 254) || a >= 224 || (a === 100 && b >= 64 && b <= 127);
}
/** Domain generated by an algorithm (DGA): long random label, few vowels */
function dgaScore(host) {
  const label = host.split('.').slice(-2, -1)[0] || '';
  if (label.length < 12 || /^xn--/.test(label)) return 0;
  const vowels = (label.match(/[aeiou]/g) || []).length / label.length;
  const digits = (label.match(/\d/g) || []).length / label.length;
  const ent = strEntropy(label);
  let s = 0;
  if (ent > 3.6) s++;
  if (vowels < 0.25) s++;
  if (digits > 0.2) s++;
  if (/[bcdfghjklmnpqrstvwxz]{5,}/.test(label)) s++;
  return s;
}

module.exports = {
  id: 'network',
  name: 'Rete & indicatori (IOC)',
  description: 'Estrae TUTTI gli indicatori di rete riga per riga: URL, domini, IPv4/IPv6, .onion, wallet crypto; rileva domini generati da algoritmi (DGA), omografi punycode, imitazioni di marchi, servizi abusati, link a eseguibili.',
  weight: 1,
  textual: true,
  applies: () => true,
  init: () => ({ binFlags: new Set(), urls: new Map(), ips: new Map(), ip6: new Set(), domains: new Map(), onions: new Map(), wallets: new Map(), flags: {} }),
  scan(unit, st, ctx) {
    const t = unit.text;
    const doc = isDoc(ctx);
    const flag = (k, loc, ev, line, tag) => {
      if ((doc || unit.kind === 'binary') && tag) tag = { ...tag, sev: { high: 'medium', medium: 'low', low: 'info' }[tag.sev] || tag.sev };
      if (unit.kind === 'binary') st.binFlags.add(k);
      (st.flags[k] ||= { locs: [], ev: new Set() });
      st.flags[k].locs.push(loc);
      st.flags[k].ev.add(truncate(ev, 120));
      if (tag) ctx.annotate(loc, line, tag);
    };
    for (const m of findAll(t, URL_RE)) {
      const u = m[0].replace(/[.,;:'")\]]+$/, '');
      const loc = unit.loc(m.index);
      if (!st.urls.has(u)) st.urls.set(u, loc);
      let h;
      try { h = new URL(u).hostname.toLowerCase(); } catch { continue; }
      if (!st.domains.has(h)) st.domains.set(h, loc);
      const line = unit.lineText(m.index);
      if (/^\d+\.\d+\.\d+\.\d+$/.test(h) && !privateIp(h)) flag('rawip', loc, u, line, { id: 'net:rawip', sev: 'medium', label: 'URL con IP diretto', desc: 'Server contattato senza nome di dominio.' });
      if (BAD_TLD.test(h)) flag('badtld', loc, u, line, { id: 'net:badtld', sev: 'medium', label: 'Dominio ad alto rischio', desc: 'Estensione di dominio molto usata per phishing/malware.' });
      if (SHORTENERS.test(h)) flag('short', loc, u, line, { id: 'net:short', sev: 'low', label: 'Link accorciato', desc: 'Nasconde la vera destinazione.' });
      if (ABUSED.test(u)) flag('abused', loc, u, line, { id: 'net:abused', sev: 'low', label: 'Servizio abusato', desc: 'Servizio spesso usato per ospitare payload.' });
      if (IP_LOOKUP.test(u)) flag('iplookup', loc, u, line, { id: 'net:iplookup', sev: 'low', label: 'Rilevamento IP pubblico', desc: 'Il codice scopre l\'IP della vittima (tipico di stealer/RAT).' });
      if (/\.(exe|scr|dll|ps1|hta|vbs|vbe|bat|cmd|msi|jar|apk|lnk|iso|img|sh|elf|dmg|pkg|jse|wsf|one|xll|scr|cpl)(\?|#|$)/i.test(u) && !/github\.com\/[^/]+\/[^/]+\/(blob|tree)\//.test(u)) flag('exeurl', loc, u, line, { id: 'net:exeurl', sev: 'high', label: 'Link a un programma', desc: 'URL che scarica direttamente un eseguibile o uno script.' });
      if (/^xn--|\.xn--/.test(h)) flag('punycode', loc, u, line, { id: 'net:puny', sev: 'medium', label: 'Dominio punycode', desc: 'Dominio con caratteri internazionali: possibile imitazione visiva (omografo).' });
      if (/https?:\/\/[^/@\s]+@/i.test(u) && !EXAMPLE.test(h)) flag('userinfo', loc, u, line, { id: 'net:at', sev: 'medium', label: 'URL ingannevole con @', desc: 'Tutto ciò che precede @ viene ignorato: il dominio reale è dopo.' });
      if (dgaScore(h) >= 3) flag('dga', loc, h, line, { id: 'net:dga', sev: 'medium', label: 'Dominio dall\'aspetto casuale', desc: 'Possibile dominio generato da algoritmo (DGA) per comando e controllo.' });
      const tokens = h.split(/[-.]/);
      const reg = registrable(h);
      const brand = BRANDS.find((b) => tokens.includes(b) && reg !== b && tokens[tokens.length - 1] !== b) && (LURE_WORDS.test(h) || BAD_TLD.test(h) || /\d/.test(reg)) ? BRANDS.find((b) => tokens.includes(b)) : null;
      if (brand && !LEGIT_BRAND_HOST.test(h) && !EXAMPLE.test(h)) flag('brand', loc, u, line, { id: 'net:brand', sev: 'medium', label: 'Imitazione di un marchio', desc: `Il dominio contiene "${brand}" ma non è il sito ufficiale.` });
      if (/^(http|ftp):\/\//i.test(u) && /(login|signin|account|password|verify|bank|pay)/i.test(u)) flag('plainlogin', loc, u, line, { id: 'net:plainlogin', sev: 'low', label: 'Login senza HTTPS', desc: 'Pagina di accesso non cifrata.' });
    }
    for (const m of findAll(t, IP_RE)) {
      const ip = m[0];
      if (privateIp(ip) || /^\d+\.0\.0\.0$/.test(ip)) continue;
      // Exclude version numbers such as 1.2.3.4 preceded by "v" or "version"
      if (/(?:v|version|ver)\s*$/i.test(t.slice(Math.max(0, m.index - 8), m.index))) continue;
      if (!st.ips.has(ip)) st.ips.set(ip, unit.loc(m.index));
    }
    for (const m of findAll(t, IPV6_RE)) st.ip6.add(m[0]);
    if (unit.kind !== 'binary') {
      for (const m of findAll(t, DOMAIN_RE)) {
        const d = m[0].toLowerCase();
        if (/\.(js|py|rb|go|io)$/.test(d) && !/\//.test(t.slice(m.index - 3, m.index))) continue;
        if (!st.domains.has(d)) st.domains.set(d, unit.loc(m.index));
      }
    }
    for (const m of findAll(t, ONION_RE)) {
      const loc = unit.loc(m.index);
      if (!st.onions.has(m[0])) st.onions.set(m[0], loc);
      ctx.annotate(loc, unit.lineText(m.index), { id: 'net:onion', sev: 'high', label: 'Indirizzo Tor', desc: 'Riferimento al dark web.' });
    }
    if (unit.kind !== 'binary') {
      for (const [coin, re, ok] of WALLETS) {
        for (const m of findAll(t, re)) {
          if (!ok(m[0])) continue;
          const key = coin + ' ' + m[0];
          const loc = unit.loc(m.index);
          if (!st.wallets.has(key)) st.wallets.set(key, loc);
          ctx.annotate(loc, unit.lineText(m.index), { id: 'net:wallet', sev: 'low', label: `Wallet ${coin}`, desc: 'Indirizzo di criptovaluta.' });
        }
      }
    }
  },
  finalize(st, ctx) {
    const out = [];
    const risky = ['executable', 'script', 'document', 'markup', 'shortcut'].includes(ctx.type.family) && !isDoc(ctx);
    const doc = isDoc(ctx);
    const F = (k, sev, title, detail) => {
      const f = st.flags[k];
      if (doc || (ctx.type.family === 'executable' && st.binFlags.has(k))) sev = { high: 'medium', medium: 'low', low: 'info' }[sev];
      if (f) out.push({ severity: sev, title: `${title} (${f.ev.size})`, detail, evidence: [...f.ev].slice(0, 8), loc: f.locs[0], locs: f.locs });
    };
    F('exeurl', 'high', 'Link per scaricare programmi', 'URL che puntano direttamente a eseguibili o script.');
    F('rawip', risky ? 'high' : 'medium', 'URL con indirizzo IP diretto', 'Connessioni a IP pubblici senza nome di dominio (tipico dei server di comando malware).');
    F('userinfo', 'high', 'URL ingannevoli con @', 'L\'indirizzo mostra un sito ma porta a un altro.');
    F('brand', 'medium', 'Domini che imitano marchi noti', 'Possibile phishing.');
    F('punycode', 'medium', 'Domini punycode (omografi)', 'Domini con caratteri che imitano lettere latine.');
    F('dga', 'medium', 'Domini generati da algoritmo (DGA)', 'Nomi casuali tipici delle botnet.');
    F('abused', risky ? 'medium' : 'low', 'Servizi spesso abusati dai malware', 'Paste, tunnel, DNS dinamici o CDN usati per ospitare payload.');
    F('badtld', 'medium', 'Domini con estensioni ad alto rischio', 'Domini (.tk, .xyz, .top, .zip…) molto usati per phishing e malware.');
    F('iplookup', 'low', 'Servizi di rilevamento IP', 'Il file scopre l\'indirizzo IP pubblico (tipico di stealer).');
    F('short', 'low', 'Link accorciati', 'URL abbreviati che nascondono la vera destinazione.');
    F('plainlogin', 'low', 'Pagine di login senza HTTPS', 'Credenziali inviate in chiaro.');
    if (st.onions.size) out.push({ severity: 'high', title: `Indirizzi della rete Tor (${st.onions.size})`, detail: 'Riferimenti al dark web, tipici di ransomware e C2.', evidence: [...st.onions.keys()].slice(0, 6), loc: [...st.onions.values()][0], locs: [...st.onions.values()] });
    if (st.wallets.size) out.push({ severity: risky ? 'medium' : 'info', title: `Indirizzi di wallet di criptovalute (${st.wallets.size})`, detail: risky ? 'Possibile richiesta di riscatto o clipper che sostituisce indirizzi.' : 'Presenti indirizzi di wallet.', evidence: [...st.wallets.keys()].slice(0, 5).map((w) => truncate(w, 70)), loc: [...st.wallets.values()][0], locs: [...st.wallets.values()] });
    if (st.ips.size && ctx.type.family === 'executable') out.push({ severity: 'low', title: `Indirizzi IP pubblici incorporati (${st.ips.size})`, detail: 'L\'eseguibile contiene IP pubblici fissi.', evidence: [...st.ips.keys()].slice(0, 10), loc: [...st.ips.values()][0], locs: [...st.ips.values()] });
    const checks = [
      ['Link diretti a eseguibili', 'exeurl'], ['URL con IP pubblico', 'rawip'], ['URL con @ ingannevole', 'userinfo'], ['Imitazione di marchi', 'brand'],
      ['Domini punycode', 'punycode'], ['Domini DGA', 'dga'], ['Servizi abusati', 'abused'], ['TLD ad alto rischio', 'badtld'], ['Rilevamento IP', 'iplookup'],
      ['Link accorciati', 'short'], ['Login senza HTTPS', 'plainlogin'],
    ].map(([n, k]) => ({ name: n, ok: !st.flags[k], note: st.flags[k] ? `${st.flags[k].ev.size}` : '0' }));
    checks.push({ name: 'Indirizzi .onion', ok: !st.onions.size }, { name: 'Wallet di criptovalute', ok: !st.wallets.size });
    return {
      findings: out, checks,
      info: { 'URL': st.urls.size, 'Domini': st.domains.size, 'IPv4 pubblici': st.ips.size, 'IPv6': st.ip6.size, '.onion': st.onions.size, 'Wallet': st.wallets.size },
      extra: { iocs: { urls: [...st.urls.keys()], domains: [...st.domains.keys()], ips: [...st.ips.keys()], ipv6: [...st.ip6], onion: [...st.onions.keys()], wallets: [...st.wallets.keys()] } },
    };
  },
};
